export const EQUIPMENT_TOTAL = EQUIPMENT.length

// Multiplier: coinsPerKill × tier multiplier = item base cost
const TIER_MULT = { cb1: 15, cb40: 20, cb70: 30, cb90: 50, boss: 50 }

export function getEquipmentCost(item) {
  if (item.source === 'shop') return item.bis ? 400 : 200
  const monster = MONSTERS_MAP.get(item.monsterId)
  if (!monster) return item.bis ? 100 : 50
  const mult = TIER_MULT[monster.tier] ?? 15
  const base = monster.coinsPerKill * mult
  return item.bis ? base * 2 : base
}
